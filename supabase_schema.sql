-- 1. Jobs Table
CREATE TABLE IF NOT EXISTS public.jobs (
    id TEXT PRIMARY KEY,
    source TEXT NOT NULL,
    title TEXT NOT NULL,
    company TEXT NOT NULL,
    location TEXT,
    work_type TEXT DEFAULT 'Unknown',
    job_type TEXT DEFAULT 'Regular',
    role_category TEXT DEFAULT 'software_engineering',
    salary TEXT,
    description TEXT,
    apply_url TEXT,
    posted_date TEXT,
    extracted_at TEXT,
    status TEXT DEFAULT 'new',
    notified_at TEXT
);

-- 2. Evaluations Table
CREATE TABLE IF NOT EXISTS public.evaluations (
    job_id TEXT PRIMARY KEY REFERENCES public.jobs (id) ON DELETE CASCADE,
    match_score INTEGER DEFAULT 0,
    match_level TEXT DEFAULT 'Low Match',
    is_applicable BOOLEAN DEFAULT TRUE,
    match_reasons TEXT DEFAULT '[]',
    matched_skills TEXT DEFAULT '[]',
    missing_skills TEXT DEFAULT '[]',
    evaluated_at TEXT,
    ai_model TEXT DEFAULT 'tri-validator-ensemble-v1',
    gemini_score INTEGER DEFAULT 0,
    ml_score INTEGER DEFAULT 0,
    preference_score INTEGER DEFAULT 0,
    validators_passed INTEGER DEFAULT 0,
    validator_details TEXT DEFAULT '{}'
);

-- 3. Scrape Runs Table
CREATE TABLE IF NOT EXISTS public.scrape_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TEXT NOT NULL,
    finished_at TEXT,
    total_scraped INTEGER DEFAULT 0,
    total_new INTEGER DEFAULT 0,
    total_high_match INTEGER DEFAULT 0,
    status TEXT DEFAULT 'running',
    log TEXT
);

-- 4. App Settings Table
CREATE TABLE IF NOT EXISTS public.app_settings (
    key TEXT PRIMARY KEY,
    value TEXT
);

-- 5. Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id TEXT PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    username TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    is_verified BOOLEAN DEFAULT FALSE,
    role TEXT DEFAULT 'user',
    created_at TEXT NOT NULL,
    last_login TEXT
);

-- 6. Email Verifications Table
CREATE TABLE IF NOT EXISTS public.email_verifications (
    id TEXT PRIMARY KEY,
    email TEXT NOT NULL,
    code TEXT NOT NULL,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    is_used BOOLEAN DEFAULT FALSE
);

-- 7. User Preferences Table
CREATE TABLE IF NOT EXISTS public.user_preferences (
    user_id TEXT PRIMARY KEY REFERENCES public.users (id) ON DELETE CASCADE,
    target_categories TEXT DEFAULT '[]',
    keywords TEXT DEFAULT '[]',
    target_location TEXT DEFAULT 'Metro Manila, Philippines',
    filter_ncr_only BOOLEAN DEFAULT TRUE,
    job_types TEXT DEFAULT '["Regular", "Internship"]',
    platforms TEXT DEFAULT '["indeed", "linkedin", "jobstreet"]',
    daily_alert_enabled BOOLEAN DEFAULT TRUE,
    alert_time TEXT DEFAULT '08:00',
    gemini_prompt TEXT DEFAULT '',
    gemini_recommendations TEXT DEFAULT '{}',
    updated_at TEXT
);

-- 8. User Sessions Table
CREATE TABLE IF NOT EXISTS public.user_sessions (
    token TEXT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL
);

-- Indexes for lightning fast queries & filtering
CREATE INDEX IF NOT EXISTS idx_jobs_status ON public.jobs (status);
CREATE INDEX IF NOT EXISTS idx_jobs_job_type ON public.jobs (job_type);
CREATE INDEX IF NOT EXISTS idx_jobs_role_category ON public.jobs (role_category);
CREATE INDEX IF NOT EXISTS idx_jobs_source ON public.jobs (source);
CREATE INDEX IF NOT EXISTS idx_evaluations_match_score ON public.evaluations (match_score DESC);
CREATE INDEX IF NOT EXISTS idx_evaluations_applicable ON public.evaluations (is_applicable);
CREATE INDEX IF NOT EXISTS idx_users_email ON public.users (email);
CREATE INDEX IF NOT EXISTS idx_users_username ON public.users (username);

-- Enable Row Level Security (RLS) with full anon access for the Early Bird client
ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.evaluations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scrape_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.email_verifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_preferences ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_sessions ENABLE ROW LEVEL SECURITY;

